#!/usr/bin/env node

var fs = require('fs');
var path = require('path');

var root = path.join(__dirname, '..');

global.document = {
  getElementById: function() { return null; }
};
global.window = global;

var performance = { now: function() { return Date.now(); } };
global.performance = performance;

eval(fs.readFileSync(path.join(root, 'js', 'engines', 'options.js'), 'utf8'));
eval(fs.readFileSync(path.join(root, 'js', 'engines', 'intelligence.js'), 'utf8'));
eval(fs.readFileSync(path.join(root, 'js', 'engines', 'checkpoint.js'), 'utf8'));
eval(fs.readFileSync(path.join(root, 'js', 'engines', 'verify.js'), 'utf8'));
eval(fs.readFileSync(path.join(root, 'js', 'engines', 'dedup-utils.js'), 'utf8'));
eval(fs.readFileSync(path.join(root, 'js', 'engines', 'core.js'), 'utf8'));
eval(fs.readFileSync(path.join(root, 'js', 'engines', 'csv.js'), 'utf8'));
eval(fs.readFileSync(path.join(root, 'js', 'engines', 'json.js'), 'utf8'));
eval(fs.readFileSync(path.join(root, 'js', 'engines', 'log.js'), 'utf8'));
eval(fs.readFileSync(path.join(root, 'js', 'engines', 'code.js'), 'utf8'));
eval(fs.readFileSync(path.join(root, 'js', 'engines', 'todo.js'), 'utf8'));
eval(fs.readFileSync(path.join(root, 'js', 'engines', 'excel.js'), 'utf8'));
eval(fs.readFileSync(path.join(root, 'js', 'engines', 'folder.js'), 'utf8'));
eval(fs.readFileSync(path.join(root, 'js', 'benchmark.js'), 'utf8'));

var results = runBenchmarkSuite();
var outPath = path.join(root, 'js', 'benchmark-results.json');
fs.writeFileSync(outPath, JSON.stringify(results, null, 2));

function buildBenchmarkDataJs(data) {
  var folderDemo = data.folderDemo || {};
  return '// Hardcoded benchmark results (generated by scripts/run-benchmark.js)\n\nvar BENCHMARK_DATA = ' +
    JSON.stringify({
      throughput: data.throughput,
      savingsDemo: data.savingsDemo,
      logDemo: data.logDemo,
      folderThroughput: data.folderThroughput,
      folderDemo: {
        totalFiles: folderDemo.total || 50,
        filesRemoved: folderDemo.filesRemoved || 0,
        linesRemoved: folderDemo.linesRemoved || 0,
        ms: folderDemo.ms || 0
      },
      summary: data.summary
    }, null, 2) + ';\n';
}

fs.writeFileSync(path.join(root, 'js', 'benchmark-data.js'), buildBenchmarkDataJs(results));

var passed = 0;
var failed = 0;

function assert(cond, msg) {
  if (cond) {
    passed++;
    console.log('  ✓ ' + msg);
  } else {
    failed++;
    console.error('  ✗ ' + msg);
  }
}

console.log('\nGeckodupe Benchmark Suite\n' + '─'.repeat(40));

console.log('\nThroughput:');
results.throughput.forEach(function(row) {
  console.log('  ' + row.label + ': ' + row.ms + 'ms · ' +
    row.removed + ' removed · ' + row.linesPerSec + ' lines/sec');
});

console.log('\nSavings demo: ' + results.savingsDemo.reductionPct + '% reduction, ' +
  results.savingsDemo.bytesSaved + ' bytes saved');

if (results.folderThroughput) {
  console.log('\nFolder throughput:');
  results.folderThroughput.forEach(function(row) {
    console.log('  ' + row.label + ': ' + row.ms + 'ms · ' + row.filesPerSec + ' files/sec');
  });
}

console.log('\nAssertions:');
assert(results.throughput.length >= 3, 'At least 3 throughput benchmarks completed');
assert(results.summary.peakLinesPerSec > 0, 'Peak throughput > 0');
assert(results.savingsDemo.removed > 0, 'Savings demo removed duplicates');
assert(results.savingsDemo.reductionPct >= 30, 'Savings demo ≥30% reduction');
assert(results.logDemo.bytesSaved > 0, 'Log demo saves bytes');

results.throughput.forEach(function(row) {
  assert(row.ms >= 0, row.label + ' completed in reasonable time');
  assert(row.remaining < row.total, row.label + ' has fewer unique than total');
});

console.log('\n' + '─'.repeat(40));
console.log('Results written to js/benchmark-results.json');
console.log('Passed: ' + passed + ' · Failed: ' + failed);

if (failed > 0) process.exit(1);
